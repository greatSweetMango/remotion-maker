#!/usr/bin/env node
/**
 * TM-175 — Regenerate `plugin/remotion-eval/src/lucide-whitelist.json`
 * from the currently-installed `lucide-react` package.
 *
 * Why a snapshot?
 * ----------------
 * The MCP plugin (`@remotion-maker/mcp-remotion-eval`) is a standalone
 * Node binary published independently — adding `lucide-react` as a
 * runtime dep would pull React + the whole 5MB icon library into a
 * pure-validation server. Instead, we snapshot the list of PascalCase
 * exports into a small JSON file checked into the repo, and the plugin
 * reads that file at startup. The in-app `src/lib/lucide-whitelist.ts`
 * continues to use the live `import * as Lucide from 'lucide-react'`
 * since the app already ships the package.
 *
 * Run after bumping `lucide-react` in package.json:
 *
 *     node scripts/codegen/lucide-whitelist-snapshot.mjs
 *
 * The denylist-sync test invariant (TM-115) extends to this snapshot:
 * `plugin/remotion-eval/test/lucide-whitelist-sync.test.ts` asserts that
 * the JSON contents equal `Object.keys(require('lucide-react')).filter(...)`
 * at run time, so any drift surfaces on next test run.
 */
import * as Lucide from 'lucide-react';
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REPO_ROOT = resolve(__dirname, '..', '..');
const OUT = resolve(REPO_ROOT, 'plugin', 'remotion-eval', 'src', 'lucide-whitelist.json');

const PASCAL = /^[A-Z][A-Za-z0-9]*$/;
const names = Object.keys(Lucide).filter((k) => PASCAL.test(k)).sort();

writeFileSync(
  OUT,
  JSON.stringify(
    {
      _comment:
        'Auto-generated by scripts/codegen/lucide-whitelist-snapshot.mjs. Do not edit by hand.',
      _generatedAt: new Date().toISOString().slice(0, 10),
      count: names.length,
      names,
    },
    null,
    2,
  ) + '\n',
);

console.log(`wrote ${names.length} lucide icon names → ${OUT}`);
